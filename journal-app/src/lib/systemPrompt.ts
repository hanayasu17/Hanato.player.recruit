/**
 * ステップ1: 文字起こし内容を整理するプロンプト
 */
export function buildOrganizePrompt(transcription: string): string {
  return `以下はユーザーが語った今日の一日の振り返りの文字起こしです。

---
${transcription}
---

これを以下の3つの観点で整理してください。ユーザーの言葉をできるだけ活かしながら、分かりやすくまとめてください。

【事実】何が起きたか（客観的な出来事）
【感情】ユーザーの生の心情（苦しみ、喜び、葛藤、怒り、感謝など）
【気づき】その日の教訓や気づき

整理した後、以下の問いかけで締めくくってください：

「今日という一日、そして今のあなたの姿を見て、神様はどう思われている（感じておられる）と思いますか？」

この問いかけは、ユーザー自身が神様の視点を意識するための最も大切な問いです。温かく、しかし真剣に問いかけてください。`;
}

